import Foundation
import CoreGraphics

var count=0
func check(_ condition: @autoclosure ()->Bool, _ name:String) {
    guard condition() else { fatalError("FAIL: \(name)") }
    count += 1; print("PASS: \(name)")
}
let right=Layout.panelOrigin(anchor:CGRect(x:1430,y:900,width:28,height:24),size:CGSize(width:640,height:56),visible:CGRect(x:0,y:0,width:1440,height:900),top:900)
check(right.x>=8 && right.x+640<=1432,"横条保持在屏幕右边界以内")
check(right.y+56==892,"横条在菜单栏下方避开刘海")
let left=Layout.panelOrigin(anchor:CGRect(x:-1910,y:1000,width:28,height:24),size:CGSize(width:360,height:56),visible:CGRect(x:-1920,y:0,width:1920,height:1000),top:1000)
check(left.x == -1912,"左侧外接屏负坐标正确")
let divider=CGRect(x:-9000,y:0,width:10000,height:24)
check(Layout.isLeft(CGRect(x:-9040,y:0,width:24,height:24),of:divider),"宽分隔线左侧的隐藏图标被识别")
check(!Layout.isLeft(CGRect(x:1010,y:0,width:24,height:24),of:divider),"右侧常驻图标不误分类")
let safe=CGRect(x:840,y:0,width:672,height:38)
check(!Layout.entryFits(CGRect(x:740,y:4,width:30,height:24),in:safe),"屏幕内但位于刘海区域的入口不算可见")
check(!Layout.entryFits(CGRect(x:830,y:4,width:30,height:24),in:safe),"部分被刘海遮住的入口不算可见")
check(Layout.entryFits(CGRect(x:1330,y:4,width:30,height:24),in:safe),"刘海右侧完整入口算可见")
check(!Layout.entryFits(CGRect(x:-1,y:981,width:30,height:24),in:safe),"系统停放在屏幕外的入口不算可见")
var drop=ShelfDropGesture(start:CGPoint(x:1200,y:16),target:CGRect(x:1284,y:4,width:30,height:24))
check(!drop.accepts(CGPoint(x:1299,y:16)),"未开始拖动时不能触发收纳")
drop.update(CGPoint(x:1299,y:16))
check(drop.accepts(CGPoint(x:1299,y:16)),"拖到入口范围内允许收纳")
check(!drop.accepts(CGPoint(x:1240,y:16)),"拖到其他菜单栏位置不收纳")
check(!drop.accepts(CGPoint(x:1299,y:70)),"拖离菜单栏不收纳")
let shifted=CGRect(x:1240,y:4,width:30,height:24)
check(drop.accepts(CGPoint(x:1255,y:16),liveTarget:shifted),"系统重排后拖到入口的新位置仍可收纳")
check(drop.accepts(CGPoint(x:1299,y:16),liveTarget:shifted),"系统重排后原入口位置仍可完成放下")
var shortDrag=ShelfDropGesture(start:CGPoint(x:1298,y:16),target:CGRect(x:1284,y:4,width:30,height:24))
shortDrag.update(CGPoint(x:1300,y:16))
check(!shortDrag.accepts(CGPoint(x:1300,y:16)),"鼠标轻微抖动不算拖拽")
let order=["A","B","C","D"]
check(ShelfOrder.moving(order,source:"A",target:"C",after:true)==["B","C","A","D"],"向右拖动插入目标图标之后")
check(ShelfOrder.moving(order,source:"D",target:"B",after:false)==["A","D","B","C"],"向左拖动插入目标图标之前")
check(ShelfOrder.moving(order,source:"D",target:"A",after:false)==["D","A","B","C"],"允许移动到最前")
check(ShelfOrder.moving(order,source:"A",target:"D",after:true)==["B","C","D","A"],"允许移动到最后")
check(ShelfOrder.moving(order,source:"B",target:"B",after:true)==order,"放回自身不改变顺序")
check(ShelfOrder.moving(order,source:"X",target:"B",after:true)==order,"失效来源不能插入新图标")
check(ShelfOrder.moving(order,source:"B",target:"X",after:false)==order,"失效目标不删除图标")
var repeated=order
for i in 0..<100 { repeated=ShelfOrder.moving(repeated,source:order[i%4],target:order[(i+1)%4],after:i%2==0) }
check(repeated.count==order.count && Set(repeated)==Set(order),"连续来回排序不会丢失或重复图标")
let expandedDivider=CGRect(x:1000,y:4.5,width:14,height:24)
check(!Layout.isFolded(CGRect(x:-1,y:981,width:40,height:24),of:expandedDivider,hasWindow:false),"系统禁用的占位图标不会误列为已收纳")
check(Layout.isFolded(CGRect(x:-4400,y:4.5,width:40,height:24),of:expandedDivider,hasWindow:true),"有效隐藏窗口仍可收纳")
check(!Layout.isFolded(CGRect(x:700,y:-1077,width:40,height:24),of:expandedDivider,hasWindow:true),"其他屏幕图标不会误列为本屏收纳")
check(!Layout.isFolded(CGRect(x:1200,y:4.5,width:40,height:24),of:expandedDivider,hasWindow:true),"恢复至右侧后离开收纳分组")
let mainDisplay=CGRect(x:0,y:0,width:1512,height:982)
check(Layout.itemFitsMenuBar(CGRect(x:1245,y:0,width:42,height:33),display:mainDisplay,minimumX:848),"33pt 刘海菜单栏窗口不误报空间不足")
check(!Layout.itemFitsMenuBar(CGRect(x:-4100,y:0,width:42,height:33),display:mainDisplay,minimumX:848),"屏幕外的折叠图标不能直接点击")
check(!Layout.itemFitsMenuBar(CGRect(x:820,y:0,width:42,height:33),display:mainDisplay,minimumX:848),"跨越刘海边缘的图标不能直接点击")
check(Layout.itemFitsMenuBar(CGRect(x:-1700,y:-1080,width:42,height:30),display:CGRect(x:-1920,y:-1080,width:1920,height:1080),minimumX:-1920),"负坐标显示器的有效菜单栏可点击")
print("\(count) checks passed")
